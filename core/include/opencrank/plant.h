/**
 * @file open_crank_plant.h
 * @brief Core definitions and simulation interface for an internal combustion engine plant.
 */

#ifndef OPEN_CRANK_PLANT_H
#define OPEN_CRANK_PLANT_H

#include <stdint.h>
#include <stdbool.h>

/* Forward declarations */
typedef struct PlantState PlantState;
typedef struct PlantParams PlantParams;

/**
 * @brief Control and external load inputs applied to the engine plant at each step.
 */
typedef struct {
    double throttle_pct;     /**< Throttle/fuel demand command, ranging from 0.0 to 100.0 % */
    double load_torque_nm;   /**< External resistive load torque in Nm (e.g., hydraulic pump, propeller) */
    bool starter_active;     /**< True if the starter motor is currently engaged */
} PlantInputs;

/**
 * @brief Dynamic physical state variables of the engine plant.
 */
struct PlantState {
    double rpm;              /**< Current crankshaft rotational speed (RPM) */
    double crank_angle_rad;  /**< Wrapped angular position of the crankshaft in radians [0, 2*PI) */
    double net_torque_nm;    /**< Net resulting torque at the crankshaft (Nm) */
    double indicated_tq_nm;  /**< Gross torque generated by combustion (Nm) */
    double friction_tq_nm;   /**< Torque lost due to mechanical friction and pumping losses (Nm) */
    double coolant_temp_c;   /**< Engine coolant temperature (°C) */
    double oil_pressure_kpa; /**< Lubricating oil pressure (kPa) */
};

/* Plant-specific polymorphic function pointers (hooks) */

/**
 * @brief Callback function to calculate gross indicated combustion torque.
 * @param state Pointer to the current engine state.
 * @param throttle_pct Current throttle/fuel command percentage [0.0, 100.0].
 * @param user_ctx Pointer to custom engine-specific context data.
 * @return Indicated torque in Newton-meters (Nm).
 */
typedef double (*PlantTorqueFn)(const PlantState *state, double throttle_pct, void *user_ctx);

/**
 * @brief Callback function to calculate resistive friction and pumping torque.
 * @param state Pointer to the current engine state.
 * @param user_ctx Pointer to custom engine-specific context data.
 * @return Friction torque in Newton-meters (Nm).
 */
typedef double (*PlantFrictionFn)(const PlantState *state, void *user_ctx);

/**
 * @brief Static configuration parameters and physical models for a specific engine plant.
 */
struct PlantParams {
    const char *name;                     /**< Human-readable identifier for the engine model */
    double inertia_kgm2;                  /**< Total rotational moment of inertia (kg·m^2) */
    double idle_rpm;                      /**< Target idle speed (RPM) */
    double max_rpm;                       /**< Maximum allowable operating speed / redline (RPM) */
    double starter_torque_nm;             /**< Torque provided by the starter motor when engaged (Nm) */
    PlantTorqueFn calc_indicated_torque;  /**< Hook for calculating combustion torque */
    PlantFrictionFn calc_friction_torque; /**< Hook for calculating friction losses */
    void *user_ctx;                       /**< Opaque pointer passed to polymorphic callbacks */
};

/**
 * @brief Initializes the engine plant state to baseline operating conditions.
 * 
 * @param state Pointer to the PlantState structure to initialize.
 * @param params Pointer to the constant PlantParams defining the engine.
 * @param initial_rpm Starting crankshaft speed in RPM.
 */
void plant_init(PlantState *state, const PlantParams *params, double initial_rpm);

/**
 * @brief Advances the engine plant simulation by a single discrete time step.
 * 
 * @param state Pointer to the PlantState structure to update.
 * @param params Pointer to the constant PlantParams defining the engine.
 * @param inputs Pointer to the current PlantInputs for this step.
 * @param dt Simulation time step delta in seconds (s).
 */
void plant_step(PlantState *state, const PlantParams *params, const PlantInputs *inputs, double dt);

#endif /* OPEN_CRANK_PLANT_H */
