#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# MISRA-oriented check of portable/ (ROADMAP.md, v0.1.x).
#
# Runs cppcheck with its MISRA addon over portable/ and compares the findings
# with a baseline, tools/misra-baseline.txt. Findings are counted per
# (rule, file), not per line: line numbers change with any edit, so a
# per-line baseline would fail for no reason.
#
#   - FAIL if a (rule, file) pair is new, or if its count went up.
#   - PASS if every count is the same or lower. Counts that went down are
#     listed, with a reminder to update the baseline.
#   - FAIL if a pair in the baseline is not covered by an approved deviation
#     in docs/misra_deviations.md, with the same count. This is what makes
#     "every finding is fixed or documented" (ROADMAP.md, v0.1.x) checkable.
#
# The baseline starts with the findings that existed when the check was
# introduced, and only goes down as findings are fixed or documented as
# deviations.
#
# A MISRA-oriented check: the addon covers only part of the rules, so passing
# it does not imply MISRA compliance. Findings are reported by rule number
# only; the rule texts are copyrighted and are not in this repository.
#
# cppcheck analyses with the target's type sizes (--platform=arm32-wchar_t4,
# a 32-bit Arm like the Cortex-M4F), not the host's.
#
# Different cppcheck versions can give different findings. The reference is
# the version CI installs (apt on ubuntu-26.04), recorded in the baseline's
# first line. tools/check_misra_docker.sh runs this script in that
# environment.
#
# Usage: tools/check_misra.sh            compare with the baseline
#        tools/check_misra.sh --update   regenerate the baseline
# Output: build/misra-report.txt, every finding as file:line:rule
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
BASELINE="$ROOT/tools/misra-baseline.txt"
DEVIATIONS="$ROOT/docs/misra_deviations.md"
REPORT="$ROOT/build/misra-report.txt"

update=0
case "${1:-}" in
    "") ;;
    --update) update=1 ;;
    *) echo "usage: tools/check_misra.sh [--update]" >&2; exit 2 ;;
esac

if ! command -v cppcheck >/dev/null 2>&1; then
    echo "FAIL: cppcheck is not installed. On Debian or Ubuntu: sudo apt-get install cppcheck" >&2
    exit 1
fi
version=$(cppcheck --version)
echo "== $version"

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$ROOT/build"

cd "$ROOT"
# cppcheck reports findings on stderr, one per line, with this template.
cppcheck_status=0
cppcheck --addon=misra --std=c11 --enable=style --platform=arm32-wchar_t4 --quiet \
    -I portable/j1939/include -I portable/machine_ctrl/include \
    --template='{file}:{line}:{id}' \
    portable 2>"$WORK/raw.txt" >"$WORK/stdout.txt" || cppcheck_status=$?

# Anything that is not a finding in the template's format means cppcheck or
# the addon did not run properly; comparing would then pass for the wrong reason.
if [[ $cppcheck_status -ne 0 ]] || grep -qvE '^[^:]+:[0-9]+:[A-Za-z0-9_.-]+$' "$WORK/raw.txt"; then
    echo "FAIL: cppcheck did not run cleanly (exit status $cppcheck_status). Its output:" >&2
    cat "$WORK/stdout.txt" "$WORK/raw.txt" >&2
    exit 1
fi

sort -t: -k1,1 -k2,2n -k3,3V "$WORK/raw.txt" >"$REPORT"
echo "   $(wc -l <"$REPORT") findings, written to ${REPORT#"$ROOT"/}"

# Counts per (rule, file): "<rule> <file> <count>", sorted by rule, then file.
awk -F: '{ n[$3 " " $1]++ } END { for (k in n) print k, n[k] }' "$REPORT" | sort -k1,1V -k2,2 >"$WORK/current.txt"

if [[ $update -eq 1 ]]; then
    {
        echo "# $version (generated by tools/check_misra.sh --update)"
        cat "$WORK/current.txt"
    } >"$BASELINE"
    echo "Baseline written: ${BASELINE#"$ROOT"/} ($(wc -l <"$WORK/current.txt") rule/file pairs)"
    echo "Now make ${DEVIATIONS#"$ROOT"/} agree: its table needs one row per pair, with the same count."
    exit 0
fi

if [[ ! -f "$BASELINE" ]]; then
    echo "FAIL: no baseline at ${BASELINE#"$ROOT"/}. Generate it with tools/check_misra.sh --update" >&2
    exit 1
fi

baseline_version=$(sed -n '1s/^# \(.*\) (generated.*$/\1/p' "$BASELINE")
if [[ "$baseline_version" != "$version" ]]; then
    echo "   note: the baseline was generated with ${baseline_version:-an unknown version}; this is $version."
    echo "         Findings can differ between versions; the version CI installs is the reference."
fi

grep -v '^#' "$BASELINE" | sort -k1,1V -k2,2 >"$WORK/baseline.txt"

# Join the two lists on (rule, file) and classify every pair.
awk '
    FNR == NR { base[$1 " " $2] = $3; next }
    { cur[$1 " " $2] = $3 }
    END {
        for (k in cur) {
            if (!(k in base))         printf "NEW   %s: %d (not in the baseline)\n", k, cur[k]
            else if (cur[k] > base[k]) printf "UP    %s: %d -> %d\n", k, base[k], cur[k]
        }
        for (k in base) {
            c = (k in cur) ? cur[k] : 0
            if (c < base[k])          printf "DOWN  %s: %d -> %d\n", k, base[k], c
        }
    }
' "$WORK/baseline.txt" "$WORK/current.txt" | sort -k2,2V -k3,3 >"$WORK/diff.txt"

if grep -qE '^(NEW|UP) ' "$WORK/diff.txt"; then
    echo "FAIL: findings that are not in the baseline (rule file: count):"
    grep -E '^(NEW|UP) ' "$WORK/diff.txt" | sed 's/^/   /'
    echo "   Every finding, with its line, is in ${REPORT#"$ROOT"/}."
    exit 1
fi

if grep -q '^DOWN ' "$WORK/diff.txt"; then
    echo "   Counts that went down:"
    grep '^DOWN ' "$WORK/diff.txt" | sed 's/^/   /'
    echo "   Update the baseline so they cannot come back: tools/check_misra.sh --update"
fi

# Every baseline pair needs a row "| <rule>, `<file>` | <count> | DEV-nnn |" in the
# deviations table, with the baseline's count, and DEV-nnn must be approved.
if [[ ! -f "$DEVIATIONS" ]]; then
    echo "FAIL: no ${DEVIATIONS#"$ROOT"/}: every baseline finding must be documented there." >&2
    exit 1
fi
awk '
    FNR == NR {
        if ($0 ~ /^\| [0-9]+\.[0-9]+, `[^`]+` \| [0-9]+ \| DEV-[0-9]+ \|/) {
            split($0, c, "|")
            rule = c[2]; sub(/^ */, "", rule); sub(/,.*/, "", rule)
            file = c[2]; sub(/^[^`]*`/, "", file); sub(/`.*/, "", file)
            n = c[3]; gsub(/ /, "", n)
            d = c[4]; gsub(/ /, "", d)
            row[rule " " file] = n " " d
        } else if ($0 ~ /^## DEV-[0-9]+:/) {
            id = $2; sub(/:$/, "", id)
        } else if ($0 ~ /^- \*\*Status:\*\* approved by the maintainer/ && id != "") {
            ok[id] = 1
        }
        next
    }
    /^#/ { next }
    {
        rule = $1; sub(/^misra-c2012-/, "", rule)   # the table says "15.5", the baseline "misra-c2012-15.5"
        k = rule " " $2
        if (!(k in row))              printf "UNDOCUMENTED  %s: %d findings, no row in the table\n", k, $3
        else {
            split(row[k], r, " ")
            if (r[1] != $3)           printf "COUNT         %s: baseline %d, table %d\n", k, $3, r[1]
            if (!(r[2] in ok))        printf "NOT APPROVED  %s: %s has no approved status\n", k, r[2]
        }
    }
' "$DEVIATIONS" "$BASELINE" >"$WORK/coverage.txt"
if [[ -s "$WORK/coverage.txt" ]]; then
    echo "FAIL: the baseline and ${DEVIATIONS#"$ROOT"/} disagree:" >&2
    sed 's/^/   /' "$WORK/coverage.txt" >&2
    exit 1
fi
echo "   every baseline pair is covered by an approved deviation"
echo "MISRA-oriented check OK: no finding beyond the baseline"
